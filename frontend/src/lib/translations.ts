export type LocaleType = keyof typeof translations;

/**
 * Translates a key if it exists in the dictionary, otherwise returns the key itself.
 */
export function translate(key: string, locale: LocaleType): string {
  const dictionary = translations[locale];
  if (key in dictionary) {
    return (dictionary as any)[key];
  }
  return key;
}
